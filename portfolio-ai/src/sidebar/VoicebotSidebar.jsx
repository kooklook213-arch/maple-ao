import { useCallback, useEffect, useRef, useState } from 'react';
import useSpeech from '../hooks/useSpeech';
import useVoiceCommands from '../hooks/useVoiceCommands';
import { askAgent } from '../services/agentAPI';
import { createDocPreview, emailProject } from '../services/googleScriptService';
import { findProject, PROJECTS } from '../services/vectorStore';
import WaveVisualizer from './WaveVisualizer';

/* ------------------------------------------------------------------ */
/*  Intent interceptor (open-webui style chat loop + Google Actions)   */
/* ------------------------------------------------------------------ */

/**
 * interceptIntent — called for EVERY user utterance (voice or text).
 * Order of resolution:
 *   1. local hotwords ("change theme …", "reset") via useVoiceCommands
 *   2. Google Workspace intents -> POST to Apps Script Web App
 *      - createDoc  : payload { action:'createDoc', title, content } -> { docUrl }
 *      - emailProject: payload { action:'emailProject', to, subject, body }
 *   3. otherwise -> LLM agent (RAG over the local vector store)
 */
async function runGoogleAction(cmd, push, speak) {
  if (cmd.type === 'createDoc') {
    const hit = cmd.project && cmd.project !== 'portfolio overview' ? findProject(cmd.project) : null;
    const p = hit ? PROJECTS.find((x) => x.id === hit.id) : null;
    const title = p ? `${p.title} — Project Summary` : 'Portfolio Overview';
    const content = p
      ? `# ${p.title}\n\n${p.blurb}\n\n## Tech Stack\n- ${p.stack.join('\n- ')}\n\nGenerated by the Aether AI voice agent.`
      : `# Portfolio Overview\n\n${PROJECTS.map((x) => `- **${x.title}** — ${x.blurb}`).join('\n')}\n\nGenerated by the Aether AI voice agent.`;

    push({ role: 'system', text: `Creating “${title}” in Google Docs…` });
    // Exact payload shape required by the Apps Script Web App:
    const res = await createDocPreview(title, content);
    if (res?.docUrl) {
      push({ role: 'doc', title, url: res.docUrl, editUrl: res.editUrl });
      speak('Your document is ready — I’ve pinned the preview right here.');
    } else if (res?.opaque) {
      push({ role: 'agent', text: 'Request sent to Google. The response was opaque (browser CORS), so check your Drive for the new doc.' });
    } else {
      push({ role: 'error', text: `Couldn’t create the doc: ${res?.error || 'unknown error'}` });
    }
    return;
  }

  if (cmd.type === 'email') {
    const hit = cmd.project ? findProject(cmd.project) : null;
    const p = hit ? PROJECTS.find((x) => x.id === hit.id) : null;
    const subject = p ? `Portfolio project: ${p.title}` : 'Portfolio intro';
    const body = p
      ? `${p.blurb}\n\nStack: ${p.stack.join(', ')}\n\n— sent from the Aether portfolio AI agent`
      : `Hi! Here is a quick tour of the portfolio:\n\n${PROJECTS.map((x) => `${x.title}: ${x.blurb}`).join('\n\n')}`;
    push({ role: 'system', text: `Emailing ${cmd.to} via Google…` });
    const res = await emailProject({ to: cmd.to, subject, body });
    if (res?.ok) { push({ role: 'agent', text: `Done — “${subject}” is on its way to ${cmd.to}.` }); speak(`Emailed ${cmd.to}.`); }
    else push({ role: 'error', text: `Email failed: ${res?.error || 'check the Apps Script deployment'}` });
    return;
  }

  if (cmd.type === 'slides') {
    push({ role: 'agent', text: 'Slide decks render inside project modals via the summarizeSlides action — hook up a deckId in PROJECTS and I’ll embed it here.' });
  }
}

export default function VoicebotSidebar({ open, onClose, onThemeChange, onReset }) {
  const [messages, setMessages] = useState([
    { role: 'agent', text: 'Hey — I’m Aether 🎙️. Ask about any project, say “change theme neon”, or tell me to “email nebula engine to you@site.com”. Tap the mic and speak.' },
  ]);
  const [input, setInput] = useState('');
  const [busy, setBusy] = useState(false);
  const chatRef = useRef(null);
  const historyRef = useRef([]);
  const inputRef = useRef(null);
  const speakRef = useRef(() => {}); // late-bound TTS (speech hook defined below)

  const push = useCallback((m) => setMessages((prev) => [...prev, { id: Math.random(), time: Date.now(), ...m }]), []);

  /* Local hotword parser (theme / reset fire side-effects through these refs) */
  const actionsRef = useRef({ onThemeChange, onReset });
  actionsRef.current = { onThemeChange, onReset };
  const parsed = useVoiceCommands({
    onTheme: (t) => actionsRef.current.onThemeChange?.(t),
    onReset: () => actionsRef.current.onReset?.(),
  });

  const handleUtterance = useCallback(async (rawText) => {
    const text = String(rawText || '').trim();
    if (!text) return;
    push({ role: 'user', text });

    // 1 & 2 — hotword / Google intent interception (parser fires theme/reset itself)
    const cmd = parsed(text);

    setBusy(true);
    try {
      if (!cmd) {
        // 3 — plain conversation -> RAG-backed LLM agent
        const reply = await askAgent(text, historyRef.current);
        historyRef.current.push({ role: 'user', content: text }, { role: 'assistant', content: reply });
        push({ role: 'agent', text: reply });
        speakRef.current(reply);
      } else if (cmd.type === 'theme') {
        push({ role: 'agent', text: `Palette switched to ${cmd.theme.toUpperCase()} — watch the core shift.` });
        speakRef.current(`Theme ${cmd.theme}.`);
      } else if (cmd.type === 'reset') {
        push({ role: 'agent', text: 'Scene reset to baseline. 🌊' });
        speakRef.current('Scene reset.');
      } else {
        await runGoogleAction(cmd, push, (t) => speakRef.current(t));
      }
    } catch (err) {
      console.error(err);
      push({ role: 'error', text: `Something broke: ${err.message}` });
    } finally {
      setBusy(false);
    }
  }, [parsed, push]);

  /* speech hook routes final transcripts straight into the interceptor */
  const speech = useSpeech({ onFinal: handleUtterance });
  speakRef.current = speech.speak;

  /* autoscroll */
  useEffect(() => {
    const el = chatRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages, busy]);

  /* focus input when opened on desktop */
  useEffect(() => { if (open && window.innerWidth > 640) inputRef.current?.focus(); }, [open]);

  /* Esc closes */
  useEffect(() => {
    const onKey = (e) => e.key === 'Escape' && open && onClose();
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [open, onClose]);

  const send = (e) => {
    e?.preventDefault();
    const v = input.trim();
    if (!v || busy) return;
    setInput('');
    handleUtterance(v);
  };

  const status = speech.listening ? 'Listening…' : speech.speaking ? 'Speaking…' : busy ? 'Thinking…' : 'Online';

  return (
    <>
      <div className={`sidebar-backdrop ${open ? 'show' : ''}`} onClick={onClose} aria-hidden="true" />
      <aside className={`ai-sidebar ${open ? 'open' : ''}`} role="complementary" aria-label="AI voice assistant">
        <header className="ai-header">
          <div className="ai-avatar">🤖</div>
          <div>
            <div className="ai-title">Aether Agent</div>
            <div className={`ai-status ${speech.listening ? 'listening' : ''}`}>
              ● {status}{speech.interim ? ` — “${speech.interim}”` : ''}
            </div>
          </div>
          <button className="ai-close" onClick={onClose} aria-label="Close assistant">✕</button>
        </header>

        <WaveVisualizer levelRef={speech.levelRef} active={speech.listening || speech.speaking} />

        <div className="ai-chat" ref={chatRef}>
          {messages.map((m) => {
            if (m.role === 'doc') {
              return (
                <div className="doc-card" key={m.id}>
                  <iframe
                    src={m.url}
                    title={m.title}
                    loading="lazy"
                    sandbox="allow-same-origin allow-popups"
                    referrerPolicy="no-referrer"
                  />
                  <a className="doc-link" href={m.editUrl || m.url} target="_blank" rel="noopener noreferrer">
                    📄 {m.title} — open document ↗
                  </a>
                </div>
              );
            }
            return <div key={m.id} className={`msg ${m.role}`}>{renderWithLinks(m.text)}</div>;
          })}
          {busy && (
            <div className="typing"><span /><span /><span /></div>
          )}
        </div>

        <div className="ai-chips">
          {['Tell me about Nebula Engine', 'Create a doc about Sentinel Agent', 'Change theme neon', 'Reset'].map((c) => (
            <button key={c} className="chip" onClick={() => handleUtterance(c)}>✦ {c}</button>
          ))}
        </div>

        <form className="ai-composer" onSubmit={send}>
          <input
            ref={inputRef}
            className="ai-input"
            value={input}
            onChange={(e) => setInput(e.target.value)}
            placeholder={speech.supported ? 'Message or speak…' : 'Message Aether…'}
            disabled={busy}
            aria-label="Message the AI assistant"
          />
          <button
            type="button"
            className={`mic-btn ${speech.listening ? 'recording' : ''}`}
            onClick={() => (speech.listening ? speech.stop() : speech.start())}
            disabled={!speech.supported}
            aria-label={speech.listening ? 'Stop listening' : 'Start voice input'}
            title={speech.supported ? 'Voice input' : 'Speech recognition unsupported in this browser'}
          >
            {speech.listening ? '■' : '🎙'}
          </button>
          <button type="submit" className="send-btn" disabled={busy || !input.trim()} aria-label="Send message">➤</button>
        </form>
      </aside>
    </>
  );
}

/* Markdown-lite renderer: **bold** + bare URLs become links. */
function renderWithLinks(text) {
  if (!text) return null;
  const parts = String(text).split(/(\*\*[^*]+\*\*|https?:\/\/\S+)/g);
  return parts.map((p, i) => {
    if (/^https?:\/\//.test(p)) return <a key={i} href={p} target="_blank" rel="noopener noreferrer">{p}</a>;
    if (/^\*\*[^*]+\*\*$/.test(p)) return <strong key={i}>{p.slice(2, -2)}</strong>;
    return p;
  });
}
